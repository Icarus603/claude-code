#!/usr/bin/env bun
/**
 * Run all 12 silent-failure audits in sequence and write a consolidated
 * inventory to docs/refactor/silent-failure-inventory.md.
 *
 * Each audit emits JSON to stdout when called without --summary; here
 * we capture each one and merge.
 */
import { execSync } from 'child_process'
import { writeFileSync } from 'fs'
import { join } from 'path'

interface AuditResult {
  pattern: string
  description: string
  totalScanned: number
  findings: Array<{
    pattern: string
    file: string
    line: number
    snippet: string
    severity: 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW'
    note: string
  }>
}

const AUDIT_DIR = join(import.meta.dirname)
const audits = [
  '01-unwired-setter-slots.ts',
  '02-await-generator-misuse.ts',
  '03-optional-chain-on-required-binding.ts',
  '04-dual-storage-divergence.ts',
  '05-empty-catch.ts',
  '06-nullish-coalesce-critical-path.ts',
  '07-stub-return-only.ts',
  '08-always-false-feature-flags.ts',
  '09-optional-method-no-guard.ts',
  '10-type-cast-traps.ts',
  '11-require-fallback.ts',
  '12-module-level-null-state.ts',
]

const results: AuditResult[] = []
for (const a of audits) {
  process.stderr.write(`Running ${a}...\n`)
  const stdout = execSync(`bun ${join(AUDIT_DIR, a)}`, {
    encoding: 'utf8',
    maxBuffer: 200 * 1024 * 1024,
  })
  results.push(JSON.parse(stdout))
}

// Build the inventory markdown.
let md = `# Silent-Failure Inventory

This file is generated by \`bun scripts/audit-silent-failures/run-all.ts\`.
DO NOT edit by hand — re-run the audit to refresh.

## Methodology

12 patterns of silent failure are scanned across \`packages/**\`. Each
pattern has its own audit script in \`scripts/audit-silent-failures/\`.
Findings are graded:

- **CRITICAL**: Active or near-certain silent failure. Fix immediately.
- **HIGH**: Looks broken given context; needs human verification.
- **MEDIUM**: Suspicious; could be intentional or a real bug.
- **LOW**: Smell; usually intentional but worth review.

## Summary

| # | Pattern | Total findings | CRITICAL | HIGH | MEDIUM | LOW |
|---|---------|---------------:|---------:|-----:|-------:|----:|
`
let totalCritical = 0, totalHigh = 0, totalMedium = 0, totalLow = 0, totalAll = 0
for (let i = 0; i < results.length; i++) {
  const r = results[i]
  const c = r.findings.filter(f => f.severity === 'CRITICAL').length
  const h = r.findings.filter(f => f.severity === 'HIGH').length
  const me = r.findings.filter(f => f.severity === 'MEDIUM').length
  const l = r.findings.filter(f => f.severity === 'LOW').length
  totalCritical += c; totalHigh += h; totalMedium += me; totalLow += l
  totalAll += r.findings.length
  md += `| ${i + 1} | ${r.pattern} | ${r.findings.length} | ${c} | ${h} | ${me} | ${l} |\n`
}
md += `| **TOTAL** | | **${totalAll}** | **${totalCritical}** | **${totalHigh}** | **${totalMedium}** | **${totalLow}** |\n\n`

md += `## Patterns in detail\n\n`
for (let i = 0; i < results.length; i++) {
  const r = results[i]
  md += `### ${i + 1}. \`${r.pattern}\`\n\n`
  md += `**Description**: ${r.description}\n\n`
  md += `**Audit script**: \`scripts/audit-silent-failures/${audits[i]}\`\n\n`
  md += `**Total scanned**: ${r.totalScanned}; **findings**: ${r.findings.length}\n\n`

  // Group by severity
  const bySeverity: Record<string, typeof r.findings> = {
    CRITICAL: [], HIGH: [], MEDIUM: [], LOW: [],
  }
  for (const f of r.findings) bySeverity[f.severity].push(f)

  for (const sev of ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW']) {
    const fs = bySeverity[sev]
    if (!fs.length) continue
    md += `#### ${sev} (${fs.length})\n\n`
    // Show up to 30 per category so the report is browsable.
    const show = fs.slice(0, 30)
    for (const f of show) {
      md += `- \`${f.file}:${f.line}\` — ${f.snippet}\n`
      md += `  - ${f.note}\n`
    }
    if (fs.length > show.length) {
      md += `- ...${fs.length - show.length} more (run audit with no flags for full JSON)\n`
    }
    md += '\n'
  }
}

const outPath = 'docs/refactor/silent-failure-inventory.md'
writeFileSync(outPath, md)
process.stderr.write(`\nWrote ${outPath} (${md.length} bytes)\n`)
process.stderr.write(`Total findings: ${totalAll} (CRITICAL=${totalCritical}, HIGH=${totalHigh}, MEDIUM=${totalMedium}, LOW=${totalLow})\n`)
